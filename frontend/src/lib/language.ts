export const LANGUAGE_STORAGE_KEY = "pantry.language";
export function readLanguage(storage?: Pick<Storage, "getItem">): Language {
  try { return storage?.getItem(LANGUAGE_STORAGE_KEY) === "en" ? "en" : "zh-Hant"; }
  catch { return "zh-Hant"; }
}
export function saveLanguage(language: Language, storage?: Pick<Storage, "setItem">) {
  try { storage?.setItem(LANGUAGE_STORAGE_KEY, language); } catch { /* In-memory choice still works. */ }
}
